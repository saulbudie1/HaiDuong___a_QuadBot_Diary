"""Generate the two ring terrains in Assets/Grounds: one with ramps, one with stairs.

    python make_terrain.py            # writes SlopeRingsGround_1.xml and StairRingsGround_1.xml
    python make_terrain.py --near     # writes only SlopeRingsGround_2.xml: the same rings 8 m closer (Test 11)

Both are heightfield scenes in the same format as SimpleUniFormRoughGround_1.xml (the heights are written inline, so
no PNG is needed) and load the same way (Scripts/rollout_terrain.py <xml> 1 0 0).

Layout, as square rings around the origin (distance d = max(|x|, |y|), metres, from the owner's design):
    0 to 10    flat at 0
    10 to 18   rises 15 degrees   (ramp, or stairs with the same average angle)
    18 to 28   flat, elevated
    28 to 35   rises 25 degrees
    35 to 45   flat, elevated
    45 to 50   rises 35 degrees   (the terrain ends at 50, so this band is cut off at the edge)
Change the BANDS table to change the layout (and SIZE if the last band is not reached).

Ramps: the height is a straight line over each band, so every face is a plane at exactly that angle (the corners
are creases along the diagonals).
Stairs: each ramp band is cut into treads of a fixed depth (TREAD) whose rise is tread * tan(angle), so the average
angle matches the ramps. A riser cannot be vertical on a heightfield: it is a steep ramp one cell wide (CELL).
"""
import math
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Assets" / "Grounds"
SIZE = 100.0                     # metres, the terrain is SIZE x SIZE with the origin in the middle
BANDS = [                        # (start d, end d, angle in degrees; 0 = flat)
    (0, 10, 0), (10, 18, 15), (18, 28, 0), (28, 35, 25), (35, 45, 0), (45, 50, 35),
]
TREAD = {15: 0.40, 25: 0.20, 35: 0.15}   # stair tread depth per slope band, metres (whole numbers of cells)

TEMPLATE = """<mujoco model="go1 feet only {title}">
  <!--
    AUTHORSHIP: this file was generated by Claude (Anthropic, via Claude Code, model Claude Sonnet 5.5) on 2026-11-04 with
    Scripts/make_terrain.py, from the layout the repo owner described: {layout}
    The grid resolution, the stair tread depths, the ground colour and the XML structure (copied from the stock
    Playground scene, as in SimpleUniFormRoughGround_1.xml) are Claude's choices. It was not hand-modelled.

    {what}
    Heightfield: {n} x {n} points over {size:g} x {size:g} m ({cell_cm:g} cm per cell). Highest point {zmax:.3f} m at the edge.
    The heights are written inline (elevation=...), already scaled so the lowest point is 0 and the highest is 1;
    the hfield size[2] below is the real height in metres. The robot starts on the flat middle at z = 0.
  -->
  <include file="go1_mjx_feetonly.xml"/>

  <statistic center="0 0 0.1" extent="0.8" meansize="0.04"/>

  <visual>
    <rgba force="1 0 0 1"/>
    <global azimuth="120" elevation="-20"/>
    <map force="0.01"/>
    <scale forcewidth="0.3" contactwidth="0.5" contactheight="0.2"/>
    <quality shadowsize="8192"/>
  </visual>

  <asset>
    <material name="groundplane" rgba="{rgba}" reflectance="0.1"/>
    <hfield name="hfield" nrow="{n}" ncol="{n}" size="{half:g} {half:g} {zmax:.4f} 1.0" elevation="
{rows}"/>
  </asset>

  <worldbody>
    <geom name="floor" type="hfield" hfield="hfield" material="groundplane" contype="1" conaffinity="0" priority="1"
      friction="1.0"/>
  </worldbody>

  <include file="sensor_feet.xml"/>

  <keyframe>
    <key name="home" qpos="
    0 0 0.35
    1 0 0 0
    0.1 0.9 -1.8
    -0.1 0.9 -1.8
    0.1 0.9 -1.8
    -0.1 0.9 -1.8"
      ctrl="0.1 0.9 -1.8 -0.1 0.9 -1.8 0.1 0.9 -1.8 -0.1 0.9 -1.8"/>
    <key name="home_higher" qpos="0 0 0.35 1 0 0 0 0 0.82 -1.63 0 0.82 -1.63 0 0.82 -1.63 0 0.82 -1.63"
      ctrl="0 0.82 -1.63 0 0.82 -1.63 0 0.82 -1.63 0 0.82 -1.63"/>
  </keyframe>
</mujoco>
"""


def ramp_height(d):
    """Height at ring distance d (metres) for the ramp terrain."""
    z = 0.0
    for a, b, deg in BANDS:
        if d <= a:
            break
        z += (min(d, b) - a) * math.tan(math.radians(deg))
    return z


def stair_height(d, cell):
    """Height at ring distance d for the stair terrain (d is a whole number of cells)."""
    z = 0.0
    for a, b, deg in BANDS:
        if d <= a:
            break
        if deg == 0:
            continue
        tread = TREAD[deg]
        rise = tread * math.tan(math.radians(deg))
        steps_total = int(round((b - a) / tread - 1e-9))          # whole steps that fit in the band
        steps = min(steps_total, int(math.floor((min(d, b) - a) / tread + 1e-9)) + 1) if d > a else 0
        # the riser sits in the cell just before the tread edge, so a vertex on the edge is already on the higher step
        z += steps * rise
    return z


def write(name, title, what, height, cell, rgba):
    n = int(round(SIZE / cell)) + 1
    c = n // 2
    grid = []
    for j in range(n):
        row = []
        for i in range(n):
            d_cells = max(abs(i - c), abs(j - c))
            row.append(height(d_cells * cell))
        grid.append(row)
    zmax = max(max(r) for r in grid)
    rows = "\n".join("      " + " ".join(f"{z / zmax:.4f}" for z in row) for row in grid)
    layout = "; ".join(f"d {a} to {b} m " + ("flat" if g == 0 else f"{g} degrees") for a, b, g in BANDS) + "."
    text = TEMPLATE.format(title=title, layout=layout, what=what, n=n, size=SIZE, half=SIZE / 2, cell_cm=cell * 100,
                           zmax=zmax, rgba=rgba, rows=rows)
    (OUT / name).write_text(text)
    print(f"{name}: {n} x {n} points, highest {zmax:.3f} m, {len(text) / 1e6:.1f} MB")


if __name__ == "__main__":
    import sys
    if "--near" in sys.argv:
        # Test 11: every band moved 8 m closer to the middle, so the 15 degree ramp starts 2 m from where the robot
        # spawns (d 0 to 2 flat, 2 to 10 at 15, 10 to 20 flat, 20 to 27 at 25, 27 to 37 flat, 37 to 42 at 35).
        # Written to a new file so SlopeRingsGround_1.xml (Tests 10 to 10.5) is not touched.
        BANDS[:] = [(a - 8 if a >= 10 else a, b - 8, g) for a, b, g in BANDS]
        write("SlopeRingsGround_2.xml", "slope rings ground 2",
              "SlopeRingsGround_2: SlopeRingsGround_1 with every band 8 m closer to the middle, so the 15 degree ramp "
              "starts 2 m from the start point (planar faces at 15, 25 and 35 degrees separated by flat steps).",
              ramp_height, 0.10, "0.40 0.62 0.48 1")
        sys.exit(0)
    write("SlopeRingsGround_1.xml", "slope rings ground 1",
          "SlopeRingsGround_1: square rings of ramps (planar faces at 15, 25 and 35 degrees) separated by flat steps.",
          ramp_height, 0.10, "0.40 0.62 0.48 1")
    write("StairRingsGround_1.xml", "stair rings ground 1",
          "StairRingsGround_1: the same rings as SlopeRingsGround_1 with the ramps cut into stairs: tread 0.40 m (rise 0.107 m) "
          "in the 15 degree band, 0.20 m (0.093 m) in the 25 degree band, 0.15 m (0.105 m) in the 35 degree band.",
          lambda d: stair_height(d, 0.05), 0.05, "0.72 0.56 0.36 1")
